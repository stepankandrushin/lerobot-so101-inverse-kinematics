"""Write src/model.c, the SO-101's model as C constants, from SO-ARM100's so101_new_calib.urdf and
its STL meshes: every joint's origin, every link's mass and centre of mass, the URDF's joint limits,
the tip frame, and the meshes' surface points for the collision check, in a tree of balls per link.

    uv run tools/gen_model.py [--urdf PATH] [--calibration FILE]

The URDF is --urdf, else SO101_URDF, else a clone of github.com/TheRobotStudio/SO-ARM100 beside this
repo (../SO-ARM100/Simulation/SO101/so101_new_calib.urdf); the meshes are read from beside it.
The points are triangles of the STL meshes sampled by area with numpy's default_rng(0), one point per
4 mm cell, so a model made again is the same. Each link's points are a tree of bounding balls (centre,
radius) in the link's own frame, halved along the longest side down to 16 points a leaf; the check
walks two links' trees together and compares points only in leaves closer than the gap. The
calibration (--calibration, else so101ik.find_calibration(), else the one compiled in now) gives the
default joint ranges compiled in for a board without a file system; the Python package reads the
file itself at every start.
"""

import argparse
import math
import os
import struct
import xml.etree.ElementTree as ET
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
URDF_IN_CLONE = Path("Simulation/SO101/so101_new_calib.urdf")
JOINTS = ["shoulder_pan", "shoulder_lift", "elbow_flex", "wrist_flex", "wrist_roll", "gripper"]
LINKS = ["base_link", "shoulder_link", "upper_arm_link", "lower_arm_link", "wrist_link", "gripper_link",
         "moving_jaw_so101_v1_link"]
SPACING = 0.004
LEAF = 16


def rot(rpy):
    r, p, y = rpy
    cr, sr, cp, sp, cy, sy = math.cos(r), math.sin(r), math.cos(p), math.sin(p), math.cos(y), math.sin(y)
    return np.array([[cy * cp, cy * sp * sr - sy * cr, cy * sp * cr + sy * sr],
                     [sy * cp, sy * sp * sr + cy * cr, sy * sp * cr - cy * sr],
                     [-sp, cp * sr, cp * cr]])


def floats(s):
    return [float(v) for v in s.split()]


def surface(path: Path, spacing: float = SPACING) -> np.ndarray:
    """Surface points of a binary STL mesh about spacing apart: triangles drawn by area, a point in each,
    one point kept per cell of spacing."""
    b = path.read_bytes()
    n = struct.unpack("<I", b[80:84])[0]
    tri = np.frombuffer(b[84:84 + 50 * n], dtype=np.dtype([("n", "<f4", 3), ("v", "<f4", (3, 3)), ("a", "<u2")]),
                        count=n)["v"].astype(float)
    area = 0.5 * np.linalg.norm(np.cross(tri[:, 1] - tri[:, 0], tri[:, 2] - tri[:, 0]), axis=1)
    rng = np.random.default_rng(0)
    k = rng.choice(n, size=int(area.sum() / (spacing / 2) ** 2) + 1, p=area / area.sum())
    u, v = rng.random((2, len(k)))
    flip = u + v > 1
    u[flip], v[flip] = 1 - u[flip], 1 - v[flip]
    pts = tri[k, 0] + u[:, None] * (tri[k, 1] - tri[k, 0]) + v[:, None] * (tri[k, 2] - tri[k, 0])
    pts = np.vstack([pts, tri.reshape(-1, 3)])
    _, keep = np.unique(np.floor(pts / spacing).astype(np.int64), axis=0, return_index=True)
    return pts[keep]


def c(v: float) -> str:
    return f"{v:.17g}"


def arr(vals) -> str:
    return "{" + ", ".join(c(float(v)) for v in vals) + "}"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--urdf", type=Path, default=None, help="so101_new_calib.urdf (SO101_URDF)")
    ap.add_argument("--calibration", type=Path, default=None, help="LeRobot's calibration file of a follower")
    a = ap.parse_args()
    a.urdf = a.urdf or Path(os.environ.get("SO101_URDF", ROOT.parent / "SO-ARM100" / URDF_IN_CLONE)).expanduser()
    if not a.urdf.is_file():
        raise SystemExit(f"{a.urdf}: no URDF. Clone https://github.com/TheRobotStudio/SO-ARM100 and give "
                         f"--urdf or SO101_URDF (its {URDF_IN_CLONE})")
    root = ET.parse(a.urdf).getroot()
    joints = {j.get("name"): j for j in root.findall("joint")}
    links = {link.get("name"): link for link in root.findall("link")}

    out = ["/* Generated by tools/gen_model.py from " + a.urdf.name + " and its meshes; do not edit. */",
           '#include "so101ik_internal.h"', ""]
    # Joints in chain order: origin rotation (row-major 3x3) and translation, the limits in radians.
    out.append("const so101_joint_def SO101_JOINTS[SO101_NJ] = {")
    for name in JOINTS:
        j = joints[name]
        o = j.find("origin")
        if floats(j.find("axis").get("xyz")) != [0, 0, 1]:
            raise SystemExit(f"{name}: only joints about their own z axis are modelled")
        lim = j.find("limit")
        out.append(f"    {{{arr(rot(floats(o.get('rpy'))).ravel())}, {arr(floats(o.get('xyz')))}, "
                   f"{c(float(lim.get('lower')))}, {c(float(lim.get('upper')))}}},  /* {name} */")
    out.append("};")
    t = joints["gripper_frame_joint"].find("origin")
    out.append(f"const so101_frame_def SO101_TIP = {{{arr(rot(floats(t.get('rpy'))).ravel())}, {arr(floats(t.get('xyz')))}}};")
    out.append("")
    # Masses and centres of mass, link frame; links in LINKS order (the URDF's tip frame weighs 1e-9 kg).
    masses, coms = [], []
    for name in LINKS:
        inertial = links[name].find("inertial")
        masses.append(float(inertial.find("mass").get("value")))
        coms += floats(inertial.find("origin").get("xyz"))
    out.append(f"const so101_real SO101_MASS[SO101_NL] = {arr(masses)};")
    out.append(f"const so101_real SO101_COM[SO101_NL][3] = {{{', '.join(arr(coms[3 * i:3 * i + 3]) for i in range(len(LINKS)))}}};")
    out.append("")

    # Mesh points per link, in the link frame, in a tree of bounding balls: each node holds a run of the
    # points, split in halves along its longest side down to LEAF points.
    pts_all, nodes, roots = [], [], []
    for name in LINKS:
        parts = []
        for vis in links[name].findall("visual"):
            o = vis.find("origin")
            r, xyz = rot(floats(o.get("rpy"))), np.array(floats(o.get("xyz")))
            v = surface(a.urdf.parent / vis.find("geometry/mesh").get("filename"))
            parts.append(v @ r.T + xyz)
        v = np.vstack(parts)
        first = len(pts_all)
        order = []

        def build(idx: np.ndarray) -> int:
            p = v[idx]
            centre = (p.min(axis=0) + p.max(axis=0)) / 2
            radius = float(np.sqrt(((p - centre) ** 2).sum(1).max())) + 1e-6
            k = len(nodes)
            nodes.append([centre, radius, 0, 0, -1, -1])
            if len(idx) <= LEAF:
                nodes[k][2], nodes[k][3] = first + len(order), len(idx)
                order.extend(idx.tolist())
                return k
            axis = int(np.argmax(p.max(axis=0) - p.min(axis=0)))
            srt = idx[np.argsort(p[:, axis], kind="stable")]
            start = first + len(order)
            left = build(srt[:len(srt) // 2])
            right = build(srt[len(srt) // 2:])
            nodes[k][2:] = [start, len(idx), left, right]
            return k

        roots.append(build(np.arange(len(v))))
        pts_all += v[order].tolist()
    out.append(f"#define NPTS {len(pts_all)}")
    out.append(f"#define NNODES {len(nodes)}")
    out.append("const float SO101_MESH_PTS[NPTS][3] = {")
    out += ["    {" + ", ".join(f"{x:.9g}f" for x in p) + "}," for p in pts_all]
    out.append("};")
    out.append("const so101_node SO101_NODES[NNODES] = {")
    out += [f"    {{{{{', '.join(f'{x:.9g}f' for x in cen)}}}, {rad:.9g}f, {first}, {n}, {left}, {right}}},"
            for cen, rad, first, n, left, right in nodes]
    out.append("};")
    out.append(f"const int SO101_LINK_ROOT[SO101_NL] = {{{', '.join(map(str, roots))}}};")
    out.append("const int SO101_MESH_NPTS = NPTS, SO101_MESH_NNODES = NNODES;")
    out.append("#ifndef SO101_SMALL")
    out.append("/* src/kin.c's scratch: the points in the world, and the check that moved each leaf's there last */")
    out.append("float so101_world_pts[NPTS][3];")
    out.append("unsigned so101_leaf_stamp[NNODES];")
    out.append("#endif")
    out.append("")

    import so101ik
    if a.calibration is None:
        try:
            a.calibration = so101ik.find_calibration()
        except so101ik.SetupError:
            pass
    cal = so101ik.read_calibration(a.calibration) if a.calibration else so101ik.default_calibration()
    out.append("/* A LeRobot calibration (" + (a.calibration.name if a.calibration else "the one compiled in before")
               + "): id, homing offset, range_min, range_max per servo. */")
    out.append("const so101_servo_cal SO101_DEFAULT_CAL[SO101_NJ] = {")
    for name, (sid, offset, lo, hi) in zip(JOINTS, cal):
        out.append(f"    {{{sid}, {offset}, {lo}, {hi}}},  /* {name} */")
    out.append("};")
    (ROOT / "src" / "model.c").write_text("\n".join(out) + "\n")
    print(f"src/model.c: {len(pts_all)} mesh points in {len(nodes)} tree nodes")


if __name__ == "__main__":
    main()
